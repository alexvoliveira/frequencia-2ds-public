begin;

create table if not exists public.teacher_feedback (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete restrict,
  class_id bigint null references public.classes(id) on delete restrict,
  subject text not null,
  message text not null,
  status text not null default 'UNREAD',
  response text null,
  handled_by uuid null references public.profiles(id) on delete set null,
  handled_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint teacher_feedback_status_check check (status in ('UNREAD','IN_REVIEW','RESOLVED')),
  constraint teacher_feedback_subject_check check (length(btrim(subject)) between 3 and 160),
  constraint teacher_feedback_message_check check (length(btrim(message)) between 3 and 8000),
  constraint teacher_feedback_response_check check (response is null or length(btrim(response)) between 3 and 8000)
);

create index if not exists teacher_feedback_teacher_status_created_idx
  on public.teacher_feedback(teacher_id,status,created_at desc);

create index if not exists teacher_feedback_class_created_idx
  on public.teacher_feedback(class_id,created_at desc);

alter table public.teacher_feedback enable row level security;
revoke all on table public.teacher_feedback from anon,authenticated,public;

create or replace function public.app_create_teacher_feedback(
  p_class_id bigint,
  p_subject text,
  p_message text
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_id bigint;
  v_subject text := nullif(left(btrim(coalesce(p_subject,'')),160),'');
  v_message text := nullif(left(btrim(coalesce(p_message,'')),8000),'');
begin
  if public.app_current_role()<>'TEACHER' then
    raise exception using errcode='42501',message='Somente professores podem enviar feedback.';
  end if;
  if v_subject is null or length(v_subject)<3 then
    raise exception using errcode='22023',message='Informe um assunto para o feedback.';
  end if;
  if v_message is null or length(v_message)<3 then
    raise exception using errcode='22023',message='Escreva o feedback antes de enviar.';
  end if;
  if p_class_id is not null and not public.app_can_access_class(p_class_id) then
    raise exception using errcode='42501',message='Você não possui acesso a esta turma.';
  end if;

  insert into public.teacher_feedback(teacher_id,class_id,subject,message,status)
  values((select auth.uid()),p_class_id,v_subject,v_message,'UNREAD')
  returning id into v_id;

  return (
    select jsonb_build_object(
      'id',id,'teacherId',teacher_id,'classId',class_id,'subject',subject,
      'message',message,'status',status,'response',response,
      'handledBy',handled_by,'handledAt',handled_at,
      'createdAt',created_at,'updatedAt',updated_at
    )
    from public.teacher_feedback where id=v_id
  );
end;
$function$;

grant execute on function public.app_create_teacher_feedback(bigint,text,text) to authenticated;
revoke execute on function public.app_create_teacher_feedback(bigint,text,text) from anon,public;

create or replace function public.app_teacher_feedback_secure(p_status text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_role text;
  result jsonb;
begin
  v_role:=public.app_current_role();

  if v_role not in ('ADMIN','TEACHER') then
    raise exception using errcode='42501',message='Você não possui permissão para acessar os feedbacks.';
  end if;

  if p_status is not null and p_status not in ('UNREAD','IN_REVIEW','RESOLVED') then
    raise exception using errcode='22023',message='Status inválido.';
  end if;

  select coalesce(jsonb_agg(row_data order by created_at desc),'[]'::jsonb)
  into result
  from (
    select
      jsonb_build_object(
        'id',f.id,'teacherId',f.teacher_id,'teacherName',tp.name,
        'classId',f.class_id,'className',c.name,'subject',f.subject,
        'message',f.message,'status',f.status,'response',f.response,
        'handledBy',f.handled_by,'handledByName',hp.name,
        'handledAt',f.handled_at,'createdAt',f.created_at,'updatedAt',f.updated_at
      ) as row_data,
      f.created_at
    from public.teacher_feedback f
    left join public.profiles tp on tp.id=f.teacher_id
    left join public.profiles hp on hp.id=f.handled_by
    left join public.classes c on c.id=f.class_id
    where (v_role='ADMIN' or f.teacher_id=(select auth.uid()))
      and (p_status is null or f.status=p_status)
  ) q;

  return result;
end;
$function$;

grant execute on function public.app_teacher_feedback_secure(text) to authenticated;
revoke execute on function public.app_teacher_feedback_secure(text) from anon,public;

create or replace function public.app_open_teacher_feedback(p_feedback_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_feedback public.teacher_feedback;
begin
  if public.app_current_role()<>'ADMIN' then
    raise exception using errcode='42501',message='Você não possui permissão para revisar feedbacks.';
  end if;

  select * into v_feedback from public.teacher_feedback where id=p_feedback_id for update;
  if not found then
    raise exception using errcode='P0002',message='Feedback não encontrado.';
  end if;

  if v_feedback.status='UNREAD' then
    update public.teacher_feedback
    set status='IN_REVIEW',handled_by=(select auth.uid()),
        handled_at=coalesce(handled_at,now()),updated_at=now()
    where id=p_feedback_id;
    select * into v_feedback from public.teacher_feedback where id=p_feedback_id;
  end if;

  return jsonb_build_object(
    'id',v_feedback.id,'status',v_feedback.status,'response',v_feedback.response,
    'handledBy',v_feedback.handled_by,'handledAt',v_feedback.handled_at,
    'handledByName',(select p.name from public.profiles p where p.id=v_feedback.handled_by)
  );
end;
$function$;

grant execute on function public.app_open_teacher_feedback(bigint) to authenticated;
revoke execute on function public.app_open_teacher_feedback(bigint) from anon,public;

create or replace function public.app_resolve_teacher_feedback(
  p_feedback_id bigint,
  p_response text
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_feedback public.teacher_feedback;
  v_response text:=nullif(left(btrim(coalesce(p_response,'')),8000),'');
begin
  if public.app_current_role()<>'ADMIN' then
    raise exception using errcode='42501',message='Você não possui permissão para resolver feedbacks.';
  end if;

  if v_response is null or length(v_response)<3 then
    raise exception using errcode='22023',message='A resposta da direção é obrigatória.';
  end if;

  select * into v_feedback from public.teacher_feedback where id=p_feedback_id for update;
  if not found then
    raise exception using errcode='P0002',message='Feedback não encontrado.';
  end if;

  if v_feedback.status<>'IN_REVIEW' then
    raise exception using errcode='42501',message='O feedback precisa estar em revisão antes de ser resolvido.';
  end if;

  update public.teacher_feedback
  set status='RESOLVED',response=v_response,handled_by=(select auth.uid()),
      handled_at=now(),updated_at=now()
  where id=p_feedback_id;

  select * into v_feedback from public.teacher_feedback where id=p_feedback_id;

  return jsonb_build_object(
    'id',v_feedback.id,'status',v_feedback.status,'response',v_feedback.response,
    'handledBy',v_feedback.handled_by,'handledAt',v_feedback.handled_at,
    'handledByName',(select p.name from public.profiles p where p.id=v_feedback.handled_by)
  );
end;
$function$;

grant execute on function public.app_resolve_teacher_feedback(bigint,text) to authenticated;
revoke execute on function public.app_resolve_teacher_feedback(bigint,text) from anon,public;

notify pgrst,'reload schema';

commit;