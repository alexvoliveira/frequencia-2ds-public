create table public.occurrence_cases (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id),
  date date not null,
  created_by uuid references auth.users(id),
  status text not null default 'UNREAD' check (status in ('UNREAD','IN_REVIEW','RESOLVED')),
  handled_by uuid references auth.users(id),
  response text,
  handled_at timestamptz,
  email_to text not null default '',
  email_status text not null default 'PENDING' check (email_status in ('PENDING','SENT','FAILED')),
  email_sent_at timestamptz,
  email_last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.occurrence_direction_managers (
  user_id uuid primary key references auth.users(id) on delete cascade,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.occurrences add column case_id bigint;
alter table public.occurrence_cases enable row level security;
alter table public.occurrence_direction_managers enable row level security;
revoke all on public.occurrence_cases from anon, authenticated, public;
revoke all on public.occurrence_direction_managers from anon, authenticated, public;
create index occurrence_cases_class_status_idx on public.occurrence_cases(class_id, status, created_at desc);
create index occurrence_cases_email_status_idx on public.occurrence_cases(email_status, created_at desc);
create index occurrences_case_id_idx on public.occurrences(case_id);
alter table public.occurrences add constraint occurrences_case_id_fkey foreign key (case_id) references public.occurrence_cases(id) on delete restrict;

alter table public.occurrence_cases add column legacy_occurrence_id bigint;
insert into public.occurrence_cases(class_id, date, created_by, status, email_status, legacy_occurrence_id)
select class_id, date, created_by, 'RESOLVED', 'SENT', id from public.occurrences;
alter table public.occurrences disable trigger occurrence_class_scope;
update public.occurrences o set case_id = c.id from public.occurrence_cases c where c.legacy_occurrence_id = o.id;
alter table public.occurrences enable trigger occurrence_class_scope;
alter table public.occurrence_cases drop column legacy_occurrence_id;
alter table public.occurrences alter column case_id set not null;


create or replace function public.app_is_occurrence_manager() returns boolean language sql stable security definer set search_path=public as $$ select exists(select 1 from public.occurrence_direction_managers m where m.user_id=(select auth.uid()) and m.active=true); $$;
grant execute on function public.app_is_occurrence_manager() to authenticated;
revoke execute on function public.app_is_occurrence_manager() from anon, public;

create or replace function public.app_create_occurrence(p_student_id bigint,p_class_id bigint,p_date date,p_type_id bigint,p_description text,p_severity text default 'LOW',p_notes text default null) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_id bigint; v_case_id bigint;
begin
  if public.app_current_role() not in ('ADMIN','TEACHER','STAFF') then raise exception using errcode='42501',message='Você não possui permissão para realizar esta ação.'; end if;
  if not public.app_can_access_class(p_class_id) then raise exception using errcode='42501',message='Você não possui acesso a esta turma.'; end if;
  if p_severity not in ('LOW','MEDIUM','HIGH') then raise exception using errcode='22023',message='Gravidade inválida.'; end if;
  if length(trim(coalesce(p_description,'')))=0 then raise exception using errcode='22023',message='A descrição é obrigatória.'; end if;
  if not exists(select 1 from public.students s where s.id=p_student_id and s.class_id=p_class_id and s.active) then raise exception using errcode='23503',message='Aluno e turma não correspondem.'; end if;
  if not exists(select 1 from public.occurrence_types where id=p_type_id and active) then raise exception using errcode='23503',message='Tipo de ocorrência inválido.'; end if;
  insert into public.occurrence_cases(class_id,date,created_by) values(p_class_id,p_date,auth.uid()) returning id into v_case_id;
  insert into public.occurrences(student_id,class_id,occurrence_type_id,date,description,severity,notes,case_id) values(p_student_id,p_class_id,p_type_id,p_date,left(trim(p_description),4000),p_severity,null,v_case_id) returning id into v_id;
  return jsonb_build_object('id',v_id,'caseId',v_case_id,'studentId',p_student_id,'classId',p_class_id,'date',p_date,'occurrenceTypeId',p_type_id,'description',left(trim(p_description),4000),'severity',p_severity);
end; $$;
grant execute on function public.app_create_occurrence(bigint,bigint,date,bigint,text,text,text) to authenticated;

create or replace function public.app_create_occurrence_bulk(p_class_id bigint,p_date date,p_type_id bigint,p_severity text,p_general_message text,p_students jsonb) returns jsonb language plpgsql security definer set search_path=public as $$
declare item jsonb; v_student_id bigint; v_description text; v_id bigint; v_case_id bigint; v_rows jsonb:='[]'::jsonb; v_count integer;
begin
  if public.app_current_role() not in ('ADMIN','TEACHER','STAFF') then raise exception using errcode='42501',message='Você não possui permissão para realizar esta ação.'; end if;
  if not public.app_can_access_class(p_class_id) then raise exception using errcode='42501',message='Você não possui acesso a esta turma.'; end if;
  if p_date is null or p_severity not in ('LOW','MEDIUM','HIGH') then raise exception using errcode='22023',message='Dados da ocorrência inválidos.'; end if;
  if nullif(left(trim(coalesce(p_general_message,'')),4000),'') is null then raise exception using errcode='22023',message='A descrição geral é obrigatória para registros em massa.'; end if;
  if not exists(select 1 from public.occurrence_types where id=p_type_id and active) then raise exception using errcode='23503',message='Tipo de ocorrência inválido.'; end if;
  if jsonb_typeof(coalesce(p_students,'[]'::jsonb))<>'array' then raise exception using errcode='22023',message='A lista de alunos é inválida.'; end if;
  select jsonb_array_length(p_students) into v_count;
  if v_count<1 or v_count>100 then raise exception using errcode='22023',message='Selecione entre 1 e 100 alunos.'; end if;
  if exists(select 1 from (select (value->>'studentId')::bigint student_id from jsonb_array_elements(p_students)) x group by student_id having count(*)>1) then raise exception using errcode='23505',message='Um aluno foi selecionado mais de uma vez.'; end if;
  insert into public.occurrence_cases(class_id,date,created_by) values(p_class_id,p_date,auth.uid()) returning id into v_case_id;
  for item in select value from jsonb_array_elements(p_students) value loop
    v_student_id:=nullif(item->>'studentId','')::bigint; v_description:=nullif(left(trim(coalesce(item->>'description','')),4000),'');
    if v_student_id is null then raise exception using errcode='22023',message='Aluno inválido na seleção.'; end if;
    if not exists(select 1 from public.students s where s.id=v_student_id and s.class_id=p_class_id and s.active) then raise exception using errcode='23503',message='Aluno não encontrado ou não pertence à turma selecionada.'; end if;
    insert into public.occurrences(student_id,class_id,occurrence_type_id,date,description,severity,notes,case_id) values(v_student_id,p_class_id,p_type_id,p_date,coalesce(v_description,left(trim(p_general_message),4000)),p_severity,null,v_case_id) returning id into v_id;
    v_rows:=v_rows||jsonb_build_array(jsonb_build_object('id',v_id,'caseId',v_case_id,'studentId',v_student_id,'classId',p_class_id,'date',p_date,'occurrenceTypeId',p_type_id,'description',coalesce(v_description,left(trim(p_general_message),4000)),'severity',p_severity));
  end loop;
  return jsonb_build_object('created',v_count,'caseId',v_case_id,'rows',v_rows);
end; $$;
grant execute on function public.app_create_occurrence_bulk(bigint,date,bigint,text,text,jsonb) to authenticated;

create or replace function public.app_occurrence_notification_payload(p_case_id bigint) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare c record; teacher record; students jsonb;
begin
  select oc.* into c from public.occurrence_cases oc where oc.id=p_case_id;
  if not found then raise exception using errcode='P0002',message='Ocorrência não encontrada.'; end if;
  if not public.app_can_access_class(c.class_id) then raise exception using errcode='42501',message='Você não possui acesso a esta ocorrência.'; end if;
  select p.name,u.email into teacher from public.occurrences o join public.profiles p on p.id=o.created_by join auth.users u on u.id=o.created_by where o.case_id=p_case_id order by o.id limit 1;
  select coalesce(jsonb_agg(jsonb_build_object('name',s.name,'description',o.description,'type',ot.name,'severity',o.severity) order by s.name),'[]'::jsonb) into students from public.occurrences o join public.students s on s.id=o.student_id join public.occurrence_types ot on ot.id=o.occurrence_type_id where o.case_id=p_case_id;
  return jsonb_build_object('caseId',c.id,'classId',c.class_id,'date',c.date,'status',c.status,'emailTo',c.email_to,'teacher',jsonb_build_object('name',coalesce(teacher.name,'Usuário'),'email',coalesce(teacher.email,'')),'className',(select name from public.classes where id=c.class_id),'students',students);
end; $$;
grant execute on function public.app_occurrence_notification_payload(bigint) to authenticated;
revoke execute on function public.app_occurrence_notification_payload(bigint) from anon, public;

create or replace function public.app_occurrence_cases_secure(p_status text default null) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare result jsonb;
begin
  if not public.app_is_occurrence_manager() then raise exception using errcode='42501',message='Você não possui permissão para cuidar das ocorrências.'; end if;
  if p_status is not null and p_status not in ('UNREAD','IN_REVIEW','RESOLVED') then raise exception using errcode='22023',message='Status inválido.'; end if;
  select coalesce(jsonb_agg(row_data order by created_at desc),'[]'::jsonb) into result from (
    select jsonb_build_object('id',oc.id,'classId',oc.class_id,'className',c.name,'date',oc.date,'status',oc.status,'handledBy',oc.handled_by,'handledByName',hp.name,'response',oc.response,'handledAt',oc.handled_at,'emailTo',oc.email_to,'emailStatus',oc.email_status,'emailSentAt',oc.email_sent_at,'emailLastError',oc.email_last_error,'createdAt',oc.created_at,'teacherName',tp.name,'teacherEmail',tu.email,'students',(select coalesce(jsonb_agg(jsonb_build_object('id',s.id,'name',s.name,'description',o.description,'type',ot.name,'severity',o.severity) order by s.name),'[]'::jsonb) from public.occurrences o join public.students s on s.id=o.student_id join public.occurrence_types ot on ot.id=o.occurrence_type_id where o.case_id=oc.id)) row_data,oc.created_at from public.occurrence_cases oc join public.classes c on c.id=oc.class_id left join public.profiles hp on hp.id=oc.handled_by left join lateral (select o.created_by from public.occurrences o where o.case_id=oc.id order by o.id limit 1) first_occ on true left join public.profiles tp on tp.id=first_occ.created_by left join auth.users tu on tu.id=first_occ.created_by where (p_status is null or oc.status=p_status)
  ) q;
  return result;
end; $$;
grant execute on function public.app_occurrence_cases_secure(text) to authenticated;
revoke execute on function public.app_occurrence_cases_secure(text) from anon, public;

create or replace function public.app_review_occurrence_case(p_case_id bigint,p_status text,p_response text default null) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_response text:=nullif(left(trim(coalesce(p_response,'')),8000),''); v_case public.occurrence_cases;
begin
  if not public.app_is_occurrence_manager() then raise exception using errcode='42501',message='Você não possui permissão para cuidar das ocorrências.'; end if;
  if p_status not in ('IN_REVIEW','RESOLVED') then raise exception using errcode='22023',message='Status inválido.'; end if;
  if p_status='RESOLVED' and v_response is null then raise exception using errcode='22023',message='A resposta da direção é obrigatória para resolver a ocorrência.'; end if;
  select * into v_case from public.occurrence_cases where id=p_case_id for update;
  if not found then raise exception using errcode='P0002',message='Ocorrência não encontrada.'; end if;
  update public.occurrence_cases set status=p_status,handled_by=auth.uid(),response=case when p_status='RESOLVED' then v_response else response end,handled_at=now(),updated_at=now() where id=p_case_id;
  select * into v_case from public.occurrence_cases where id=p_case_id;
  return jsonb_build_object('id',v_case.id,'status',v_case.status,'handledBy',v_case.handled_by,'response',v_case.response,'handledAt',v_case.handled_at);
end; $$;
grant execute on function public.app_review_occurrence_case(bigint,text,text) to authenticated;
revoke execute on function public.app_review_occurrence_case(bigint,text,text) from anon, public;

create or replace function public.app_delete_occurrence(p_id bigint) returns void language plpgsql security definer set search_path=public as $$
declare v_case_id bigint;
begin
  if public.app_current_role()<>'ADMIN' then raise exception using errcode='42501',message='Você não possui permissão para excluir este registro.'; end if;
  select case_id into v_case_id from public.occurrences where id=p_id and public.app_can_access_class(class_id);
  if v_case_id is null then raise exception using errcode='42501',message='Você não possui acesso a este registro.'; end if;
  delete from public.occurrences where id=p_id;
  if not found then raise exception using errcode='P0002',message='Ocorrência não encontrada.'; end if;
  if not exists(select 1 from public.occurrences where case_id=v_case_id) then delete from public.occurrence_cases where id=v_case_id; end if;
end; $$;
grant execute on function public.app_delete_occurrence(bigint) to authenticated;

